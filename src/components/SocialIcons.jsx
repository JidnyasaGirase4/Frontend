export function SocialIcon({ name, size = 16 }) {
  return (
    <svg viewBox="0 0 24 24" width={size} height={size} fill="currentColor" aria-hidden="true">
      <path d={socialPaths[name]} />
    </svg>
  )
}

function SocialIcons({ className = '' }) {
  const { site } = useContent()
  const hrefFor = (label) => site.socials?.find((s) => s.label === label)?.href || '#'

  return (
    <div className={`social-icons ${className}`}>
      {socials.map((social) => (
        <a key={social.label} href={hrefFor(social.label)} className={social.className} aria-label={social.label}>
          <svg viewBox="0 0 24 24" width="16" height="16" fill="currentColor" aria-hidden="true">
            <path d={social.path} />
          </svg>
        </a>
      ))}
    </div>
  )
}

export default SocialIcons
